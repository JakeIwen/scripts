"""Render the shell and boot-time registry from the Python lock vocabulary.

Run from the checkout with python3 -m pi.generate_backup_lock_registry [--check].
Generation is a development/deployment check, never a shell job's runtime step.
"""
import argparse
from pathlib import Path
import shlex

from pi.scripts.backup import backup_locks as locks


GENERATED = '# Generated by python3 -m pi.generate_backup_lock_registry; do not edit.\n'
REGISTRY = '/run/lock/vanpi-backup'
SHELL_VARIABLES = {
    locks.LockClass.JOB: 'BACKUP_JOB_KINDS',
    locks.LockClass.DISK: 'BACKUP_DISK_LABELS',
    locks.LockClass.DATA: 'BACKUP_DATA_NAMES',
    locks.LockClass.CLOUD: 'BACKUP_CLOUD_SLOT',
}


def generated_files():
    shell = '#!/bin/bash\n' + GENERATED
    tmpfiles = GENERATED + '''# Shared by root-run backup jobs and pi-initiated lifecycle checks. Keep the
# inode root-owned so /run/lock's sticky-directory protections cannot make a
# root abort helper reject a lock previously opened by pi.
f /run/lock/vanpi_backup.lock 0660 root pi -
# Resource-specific backup locks (pi/docs/backup/CONCURRENCY.md). The registry
# is fixed: jobs fail closed on an unknown kind, label or data set instead of
# creating lock files at runtime.
d /run/lock/vanpi-backup 0770 root pi -
'''
    for kind, names in locks.LOCK_NAMES.items():
        value = ' '.join(shlex.quote(name) for name in names)
        if kind is not locks.LockClass.CLOUD:
            value = f'({value})'
        shell += f'{SHELL_VARIABLES[kind]}={value}\n'
        for name in names:
            tmpfiles += f'f {REGISTRY}/{kind.value}-{name}.lock 0660 root pi -\n'
    return {'scripts/backup/backup_lock_registry.sh': shell,
            'tmpfiles.d/vanpi-backup.conf': tmpfiles}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='refuse stale output without writing')
    args = parser.parse_args(argv)
    stale = []
    for relative, content in generated_files().items():
        path = Path(__file__).resolve().parent / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding='utf-8') != content:
                stale.append(relative)
        else:
            path.write_text(content, encoding='utf-8')
    if stale:
        parser.exit(1, 'Stale backup registry artifacts: ' + ', '.join(stale)
                    + '\nRun python3 -m pi.generate_backup_lock_registry\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
