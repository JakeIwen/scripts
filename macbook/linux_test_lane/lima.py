"""Lima adapter: the VM's template and the limactl calls that manage it."""
import json
import subprocess
import tempfile

INSTANCE = 'linux-test-lane'
LIMACTL = 'limactl'


def quoted(value):
    # A JSON string is a valid YAML double-quoted scalar, whatever the path holds.
    return json.dumps(str(value))


def render_template(pins, source_mount):
    """The instance's lima.yaml; edit pins.env rather than a created instance."""
    return f'''# Generated by macbook/linux_test_lane from pins.env; recreate to change it.
vmType: vz
arch: aarch64
cpus: {pins.cpus}
memory: {quoted(pins.memory)}
disk: {quoted(pins.disk)}
images:
- location: {quoted(pins.image_url)}
  arch: aarch64
  digest: {quoted(pins.image_digest)}
# The checkout is only a sync source; tests run on VM-local disk.
mountType: virtiofs
mounts:
- location: {quoted(source_mount)}
  writable: false
user:
  name: {quoted(pins.user)}
  uid: {pins.uid}
  home: {quoted(pins.home)}
containerd:
  system: false
  user: false
ssh:
  loadDotSSHPubKeys: false
  forwardAgent: false
# Test servers bind ports; never forward them onto the Mac's loopback.
portForwards:
- guestIP: "127.0.0.1"
  proto: any
  ignore: true
- guestIP: "0.0.0.0"
  proto: any
  ignore: true
'''


def limactl(*args, capture=False, check=True, input=None):
    return subprocess.run([LIMACTL, *args], check=check, input=input,
                          capture_output=capture, text=True)


def instance_info(name=INSTANCE):
    """limactl's record for the instance, or None when it doesn't exist."""
    listing = limactl('list', '--json', capture=True).stdout
    for line in listing.splitlines():
        record = json.loads(line)
        if record.get('name') == name:
            return record
    return None


def create(template, name=INSTANCE):
    with tempfile.NamedTemporaryFile('w', suffix='.yaml', prefix=name + '-') as stream:
        stream.write(template)
        stream.flush()
        limactl('create', '--tty=false', '--name', name, stream.name)


def start(name=INSTANCE):
    limactl('start', '--tty=false', name)


def stop(name=INSTANCE):
    limactl('stop', name)


def delete(name=INSTANCE):
    limactl('delete', '--force', name)


def shell_command(*command, workdir=None, name=INSTANCE):
    args = [LIMACTL, 'shell']
    if workdir is not None:
        args += ['--workdir', str(workdir)]
    return args + [name, '--', *map(str, command)]


def run_in_vm(*command, workdir=None, capture=False, check=True, input=None, name=INSTANCE):
    return subprocess.run(shell_command(*command, workdir=workdir, name=name), check=check,
                          input=input, capture_output=capture, text=True)
